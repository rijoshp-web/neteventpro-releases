'use strict';
const { EventEmitter } = require('node:events');
const { parse, SEVERITIES } = require('./parser');
const SEVX = require('./sev');
const { RuleEngine } = require('./rules');
const { Forwarder, TrapForwarder } = require('./forwarder');
const { Replacer } = require('./replace');
const { RawLog } = require('./rawlog');
const { AlertMailer } = require('./mailer');
const { Notifier } = require('./notify');
const { tagMessage } = require('./vendors');
const { parseSevs } = require('./query');
const { ENTERPRISES: ENTERPRISE_NAMES } = require('./traps');
const { nameOf: entName } = require('./enterprises');
const VENDOR_TAGS = { cisco: 'Cisco', apc: 'APC', dell: 'Dell', hp: 'HP / HPE', hpe: 'HP / HPE', eltek: 'Eltek', spectracom: 'Spectracom', eventide: 'Eventide', dnwp: 'DNWP', juniper: 'Juniper', fortinet: 'Fortinet', aruba: 'Aruba', mikrotik: 'MikroTik' };

const RATE_WINDOW = 120; // seconds of per-second history kept in memory
const MAX_MESSAGE_BYTES = 16384;
const MAX_DEVICES = 10000;   // spoofed source addresses must not grow the device list without limit

/** Central pipeline: parse -> rules -> live buffer -> stats/devices -> storage -> forwarding. */
class Engine extends EventEmitter {
  constructor(config, store) {
    super();
    this.config = config; this.store = store;
    this.rules = new RuleEngine(); this.forwarder = new Forwarder(); this.trapForwarder = new TrapForwarder();
    this.replacer = new Replacer(); this.rawlog = new RawLog(config.dir); this.mail = new AlertMailer(config); this.notify = new Notifier(config, this.mail); this.rules.noisy = (ids) => this.notify.noisy(ids);
    this.nextId = store.maxId() + 1; this.nextSeq = store.maxSeq();
    this.live = [];                         // newest last
    this.pending = [];                      // batch waiting for SSE flush
    this.devices = new Map();
    this.totals = { received: 0, dropped: 0, bySeverity: new Array(10).fill(0), since: Date.now(), peakEps: 0 };
    this.secCounts = new Int32Array(RATE_WINDOW); this.secStamp = new Float64Array(RATE_WINDOW);
    this.dirtyDevices = new Set();
    this.seriesCache = null;

    for (const d of store.loadDevices()) {
      const ips = d.ips ? String(d.ips).split(',').filter(Boolean) : [];
      this.devices.set(d.key, { ...d, srcIps: ips, srcIp: ips[ips.length - 1] || d.key, legacy: !ips.length, sev: new Array(10).fill(0), silent: false, lastMessage: '', lastSeverity: 6 });
    }
    this.mergeDuplicateDevices();
    this.applyConfig(config.get());
    config.onChange((c) => this.applyConfig(c));

    this.timers = [
      setInterval(() => this.flushPending(), 40),
      setInterval(() => this.checkSilent(), 30000),
      setInterval(() => this.persistDevices(), 30000),
      setInterval(() => this.maintenance(), 3600000)
    ];
    for (const t of this.timers) t.unref?.();
    setTimeout(() => this.maintenance(), 15000).unref?.();
  }

  applyConfig(c) {
    this.rules.load([...(c.rules || []), ...(this.extraRules ? this.extraRules() : [])]);      // extraRules: the rules of SNMP polling (thresholds, no answer), not listed on the Rules page
    this.forwarder.configure(c.forwardTargets); this.trapForwarder.configure(c.trapForwardTargets);
    this.replacer.load(c.replacements);
    require('./trapcols').setReplacements(c.replacements);
    this.rawlog.configure(c.rawLogEnabled);
    while (this.live.length > c.liveBufferSize) this.live.shift();
  }

  // ---- ingestion --------------------------------------------------------
  handlePacket(buf, srcIp, proto, opts = {}) {
    if (!buf || !buf.length) return;
    // A syslog message is normally well under 2 KB. Cap what we keep so a sender of 64 KB datagrams cannot fill memory:
    // the live view holds thousands of messages and every one is stored twice (text and original packet).
    if (buf.length > MAX_MESSAGE_BYTES) buf = buf.subarray(0, MAX_MESSAGE_BYTES);
    const text = buf.toString('utf8');
    // some devices pack several syslog lines in one datagram
    const parts = text.includes('\n') ? text.split(/\r?\n(?=<\d{1,3}>)/) : [text];
    for (const p of parts) { if (p.trim()) { const m = parse(p, srcIp); if (opts.ts) m.ts = opts.ts; if (opts.via) (m.tags ||= []).push('probe:' + opts.via); this.process(m); } }
  }

  /** @param {object} msg parsed message  @param {boolean} internal generated by NetEventPro itself */
  process(msg, internal = false) {
    const cfg = this.config.get();
    this.totals.received++;
    this.bumpRate();

    if (!internal) {
      if (!msg.host || msg.host === '-') msg.host = msg.srcIp;
      // a device is identified by the name it writes in its own message (or, when it sends none, by its address), not by the address
      // the packet came from: one device that sends from several addresses stays one device
      msg.devKey = this.resolveKey(String(msg.host).toLowerCase().slice(0, 253), msg.srcIp);
      const al = cfg.deviceAliases; const alias = al && (al[msg.devKey] ?? al[msg.host] ?? al[msg.srcIp]);
      if (alias) msg.host = alias;
    }
    msg.tags = msg.tags || [];
    msg.source = !internal && msg.source === 'snmp' ? 'snmp' : 'syslog';     // only the trap receiver sets this: a syslog sender cannot claim to be a trap

    // text replacement (IP -> name etc.) runs before rules, so rules, search and alerts all see the replaced text; msg.raw stays original
    this.replacer.apply(msg);
    if (msg.source === 'snmp') {      // a trap view can say which of its columns is the severity of the trap: then alarms, rules, colours and filters all follow it
      const c2 = cfg.uiPrefs || {}, sv = require('./trapcols').severityOf(c2.trapViews, c2.trapViewDefault, msg);
      if (sv !== null && sv !== msg.severity) { msg.severity = sv; msg.severityName = SEVERITIES[sv]; }
    }
    if (!internal && cfg.vendorParsers !== false) tagMessage(msg, cfg.vendorParsers || {});   // adds tags like cisco / link-down; rules below can match them
    if (msg.message.length > 2 * MAX_MESSAGE_BYTES) msg.message = msg.message.slice(0, 2 * MAX_MESSAGE_BYTES);

    const maint = (!internal || msg.poll) && this.maint ? this.maint.forMessage(msg) : null;
    if (maint && !msg.tags.includes('maintenance')) msg.tags.push('maintenance');
    const res = this.rules.apply(msg, !!maint);
    if (res.drop) { this.totals.dropped++; return; }

    msg.id = this.nextId++; msg.seq = ++this.nextSeq[msg.source === 'snmp' ? 'snmp' : 'syslog'];
    msg.sound = res.sound; msg.notify = res.notify;
    this.totals.bySeverity[msg.severity]++;

    if (!internal) this.touchDevice(msg);

    this.live.push(msg);
    if (this.live.length > cfg.liveBufferSize) this.live.splice(0, this.live.length - cfg.liveBufferSize);
    this.pending.push(msg);
    this.store.enqueue(msg);
    this.rawlog.write(msg);
    if (!internal) { if (msg.source === 'snmp') this.trapForwarder.send(msg); else this.forwarder.send(msg); }

    // flap detection (1.40): a rule's item that keeps changing is told once as "flapping"; its single alerts are held back until it is quiet
    const flap = new Map();      // rule id -> 'start' | true
    if (this.alarms) {
      for (const c of res.clears) this.alarms.flapClearEvent(c.id, msg, c.alarmBy);
      for (const r of res.alarms) { const f = this.alarms.flapEvent(msg, r); if (f) flap.set(r.id, f); }
    }
    const held = (rule) => rule && flap.get(rule.id) === true;
    const alertMsg = (rule) => (rule && flap.get(rule.id) === 'start' ? { ...msg, message: `FLAPPING (many changes in a short time): ${msg.message}` } : msg);
    for (const w of res.webhooks) if (!held(w.rule)) this.callWebhook(w, msg);
    for (const e of res.emails) if (!held(e.rule)) this.mail.enqueue(e, msg);
    for (const n of res.notifs) if (!held(n.rule)) this.notify.dispatch(n.profiles, 'alert', { rule: n.rule, suppressed: n.suppressed, msg: alertMsg(n.rule), report: n.report });
    if (this.alarms) {
      for (const c of res.clears) this.alarms.clearBy(c.id, msg, c.by, c.alarmBy);
      for (const r of res.alarms) { const f = flap.get(r.id); if (f) this.alarms.flapRaise(msg, r, f === 'start'); else this.alarms.raise(msg, r); }
    }
  }

  bumpRate() {
    const s = Math.floor(Date.now() / 1000), i = s % RATE_WINDOW;
    if (this.secStamp[i] !== s) { this.secStamp[i] = s; this.secCounts[i] = 0; }
    this.secCounts[i]++;
  }

  /** messages per second for the last RATE_WINDOW seconds, oldest first */
  rateSeries() {
    const now = Math.floor(Date.now() / 1000); const out = [];
    for (let s = now - RATE_WINDOW + 1; s <= now; s++) {
      const i = s % RATE_WINDOW; out.push(this.secStamp[i] === s ? this.secCounts[i] : 0);
    }
    return out;
  }
  currentEps() {
    const r = this.rateSeries(); const last = r.slice(-6, -1); // skip the partial current second
    const eps = last.reduce((a, b) => a + b, 0) / (last.length || 1);
    if (eps > this.totals.peakEps) this.totals.peakEps = Math.round(eps);
    return Math.round(eps * 10) / 10;
  }

  flushPending() {
    if (!this.pending.length) return;
    const batch = this.pending; this.pending = [];
    this.emit('messages', batch);
  }

  // ---- devices ----------------------------------------------------------
  /** One device, one row. A device that sends syslog under its host name and traps under its address (a trap has no host name) is the same device: a row named by an
   *  address is joined to the device that already sends from that address, but only when exactly one device does (a relay that forwards for several hosts stays as it is). */
  static isAddr(k) { return /^\d{1,3}(\.\d{1,3}){3}$/.test(k) || (/:/.test(k) && /^[0-9a-f:.]+$/i.test(k)); }
  namedDeviceAt(ip, except = '') { const hit = []; for (const o of this.devices.values()) if (o.key !== except && !Engine.isAddr(o.key) && (o.srcIps || []).includes(ip)) hit.push(o); return hit.length === 1 ? hit[0] : null; }
  /** the key a message belongs to: its own, or the named device at that address when the message is named by the address only */
  resolveKey(key, srcIp) {
    if (!Engine.isAddr(key)) return key;
    const o = this.namedDeviceAt(srcIp, key); if (!o) return key;
    const old = this.devices.get(key); if (old) this.absorb(o, old);              // an address-named row from before: join it now
    return o.key;
  }
  absorb(into, from) {
    into.count = (into.count || 0) + (from.count || 0); into.sys = (into.sys || 0) + (from.sys || 0); into.traps = (into.traps || 0) + (from.traps || 0);
    into.firstSeen = Math.min(into.firstSeen || Infinity, from.firstSeen || Infinity); into.lastSeen = Math.max(into.lastSeen || 0, from.lastSeen || 0);
    into.lastTrap = Math.max(into.lastTrap || 0, from.lastTrap || 0); into.lastSyslog = Math.max(into.lastSyslog || 0, from.lastSyslog || 0);
    if (!into.vendor && from.vendor) into.vendor = from.vendor;
    if (Array.isArray(from.sev)) into.sev = (into.sev || new Array(10).fill(0)).map((n, i) => n + (from.sev[i] || 0));
    for (const ip of from.srcIps || []) if (!into.srcIps.includes(ip)) into.srcIps.push(ip);
    this.devices.delete(from.key); this.store.deleteDevice(from.key); this.dirtyDevices.add(into.key);
  }
  /** at start: join rows that are the same device (see above) */
  mergeDuplicateDevices() {
    for (const d of [...this.devices.values()]) {
      if (!Engine.isAddr(d.key)) continue;
      const o = this.namedDeviceAt(d.srcIps?.[d.srcIps.length - 1] || d.key, d.key) || this.namedDeviceAt(d.key, d.key);
      if (o) this.absorb(o, d);
    }
  }
  touchDevice(msg) {
    const key = msg.devKey || msg.srcIp;
    let d = this.devices.get(key);
    const now = msg.ts;
    if (!d) d = this.adoptLegacy(msg, key);
    if (!d && this.devices.size >= MAX_DEVICES) { this.devicesIgnored = (this.devicesIgnored || 0) + 1; return; }
    if (!d) {
      d = { key, srcIp: msg.srcIp, srcIps: [msg.srcIp], host: msg.host, firstSeen: now, lastSeen: now, count: 0, sev: new Array(10).fill(0), silent: false, lastMessage: '', lastSeverity: 6 };
      this.devices.set(key, d);
      if (!Engine.isAddr(key)) { const old = this.devices.get(String(msg.srcIp).toLowerCase()); if (old && old.key !== key && this.namedDeviceAt(msg.srcIp) === d) this.absorb(d, old); }   // it was known by its address so far (from traps): same device
      this.emit('device-new', d);
    }
    d.legacy = false;
    if (d.srcIp !== msg.srcIp || !d.srcIps.includes(msg.srcIp)) {            // the same device sent from another address
      d.srcIp = msg.srcIp; d.srcIps = d.srcIps.filter((x) => x !== msg.srcIp); d.srcIps.push(msg.srcIp); if (d.srcIps.length > 8) d.srcIps.shift();
    }
    d.host = msg.host; d.lastSeen = now; d.count++; d.sev[msg.severity]++;
    if (msg.source === 'snmp') { d.traps = (d.traps || 0) + 1; d.lastTrap = now; } else { d.sys = (d.sys || 0) + 1; d.lastSyslog = now; }
    if (!d.vendor) {
      const t = (msg.tags || []).map((x) => VENDOR_TAGS[String(x).toLowerCase()]).find(Boolean);
      d.vendor = t || (msg.source === 'snmp' && msg.entNum ? entName(msg.entNum) : '');       // a trap sender gets the maker of its own MIB tree, or "Enterprise N" when the number is not in the list
    }
    d.lastMessage = msg.message.slice(0, 200); d.lastSeverity = msg.severity;
    if (d.silent) {
      d.silent = false;
      this.internalMessage(5, `Device ${d.host} (${d.srcIp}) is sending again after being silent`, d.host, 'silent');
    }
    this.dirtyDevices.add(key);
  }

  /** a device list saved by an older version was keyed by address: take over that entry when it is the same device */
  adoptLegacy(msg, key) {
    for (const ip of new Set([msg.srcIp, ...(msg.host && msg.host !== msg.srcIp ? [] : [])])) {
      const old = this.devices.get(ip);
      if (old && old.legacy && old.key !== key && String(old.host || '').toLowerCase() === String(msg.host).toLowerCase()) {
        this.devices.delete(old.key); this.store.deleteDevice(old.key);
        old.key = key; this.devices.set(key, old); return old;
      }
    }
    return null;
  }

  checkSilent() {
    const cfg = this.config.get();
    const mins = +cfg.silentDeviceMinutes || 0;
    const muted = new Set(cfg.mutedDevices || []);
    const info = cfg.deviceInfo || {};
    for (const d of this.devices.values()) {
      const own = +(info[d.key] || {}).expectMin || 0, m = own || mins;           // a device can have its own "must report every N minutes"
      if (!m) continue;
      const limit = Date.now() - m * 60000;
      if (d.silent || this.isMuted(muted, d) || (!own && d.count < 3)) continue;
      if (this.maint && this.maint.forDevice([d.key, d.host, d.srcIp, ...(d.srcIps || [])])) continue;      // planned work: not an outage
      if (d.lastSeen < limit) {
        d.silent = true;
        this.internalMessage(3, `No messages from ${d.host} (${d.srcIp}) for ${m}+ minutes — last seen ${new Date(d.lastSeen).toISOString()}`, d.host, 'silent');
      }
    }
  }

  /** NetEventPro's own messages (health checks, silent devices, who changed what). kind: 'health' | 'silent' | 'audit' | 'other'; each kind can be switched off in Settings → System messages */
  internalMessage(severity, text, host = 'NetEventPro', kind = 'other', msgid = '') {
    const sm = this.config.get().systemMessages || {}; if (sm.all === false || sm[kind] === false) return;
    const now = new Date();
    this.process({
      ts: now.getTime(), devTs: now.getTime(), srcIp: 'neteventpro', host, facility: 5, severity,
      facilityName: 'syslog', severityName: SEVERITIES[severity], app: 'neteventpro', pid: '', msgid,
      message: text, format: 'internal', sd: null, raw: `<${5 * 8 + SEVX.syslogNum(severity)}>neteventpro: ${text}`
    }, true);
  }

  isMuted(muted, d) { return muted.has(d.key) || d.srcIps.some((ip) => muted.has(ip)); }

  persistDevices() {
    if (!this.dirtyDevices.size) return;
    const list = [...this.dirtyDevices].map(k => this.devices.get(k)).filter(Boolean);
    this.dirtyDevices.clear();
    this.store.saveDevices(list);
  }

  deviceList() {
    const cfg = this.config.get(); const muted = new Set(cfg.mutedDevices || []); const now = Date.now(); const al = cfg.deviceAliases || {};
    return [...this.devices.values()].map(d => ({
      key: d.key, srcIp: d.srcIp, srcIps: d.srcIps, host: d.host, alias: al[d.key] ?? d.srcIps.map((ip) => al[ip]).find(Boolean) ?? '', firstSeen: d.firstSeen, lastSeen: d.lastSeen,
      count: d.count, sev: d.sev, silent: d.silent, muted: this.isMuted(muted, d),
      idle: !d.silent && (+cfg.silentDeviceMinutes || 0) > 0 && now - d.lastSeen > cfg.silentDeviceMinutes * 60000,   // quiet for a while, but too few messages to be sure it should be sending regularly
      ageSec: Math.round((now - d.lastSeen) / 1000), lastMessage: d.lastMessage, lastSeverity: d.lastSeverity,
      sys: d.sys || 0, traps: d.traps || 0, lastSyslog: d.lastSyslog || 0, lastTrap: d.lastTrap || 0, vendor: d.vendor || '',
      group: (cfg.deviceInfo?.[d.key] || {}).group || '', note: (cfg.deviceInfo?.[d.key] || {}).note || '', expectMin: (cfg.deviceInfo?.[d.key] || {}).expectMin || 0,
      overdue: !!((cfg.deviceInfo?.[d.key] || {}).expectMin && now - d.lastSeen > cfg.deviceInfo[d.key].expectMin * 60000),
      openAlarms: this.alarms ? this.alarms.openFor([d.key, d.srcIp, ...(d.srcIps || [])]) : 0
    })).sort((a, b) => b.lastSeen - a.lastSeen);
  }

  forgetDevice(key) { this.devices.delete(key); this.store.deleteDevice(key); }

  // ---- webhooks ---------------------------------------------------------
  async callWebhook(w, msg) {
    const hook = (this.config.get().webhooks || []).find(h => h.name === w.hook && h.enabled !== false);
    if (!hook || !hook.url) return;
    const text = `[${msg.severityName.toUpperCase()}] ${msg.host} ${msg.app ? msg.app + ': ' : ''}${msg.message}` +
      (w.suppressed ? `\n(+${w.suppressed} similar alerts suppressed in the last cooldown window)` : '');
    try {
      const ctrl = new AbortController(); const to = setTimeout(() => ctrl.abort(), 5000);
      const r = await fetch(hook.url, {
        method: 'POST', headers: { 'content-type': 'application/json' }, signal: ctrl.signal, redirect: 'error',
        // "text" works for Slack/Teams/Mattermost incoming webhooks; extra fields help custom receivers (n8n, Node-RED...)
        body: JSON.stringify({
          text, rule: w.rule.name, suppressed: w.suppressed,
          message: { time: new Date(msg.ts).toISOString(), host: msg.host, srcIp: msg.srcIp, severity: msg.severityName, facility: msg.facilityName, app: msg.app, text: msg.message }
        })
      });
      clearTimeout(to);
      this.emit('webhook', { hook: hook.name, ok: r.ok, status: r.status });
    } catch (e) { this.emit('webhook', { hook: hook.name, ok: false, error: e.message }); }
  }

  // ---- queries for the dashboard ---------------------------------------
  recent(filter = {}, limit = 500) {
    const f = makeLiveFilter(filter);
    const out = [];
    for (let i = this.live.length - 1; i >= 0 && out.length < limit; i--) if (f(this.live[i])) out.push(this.live[i]);
    return out.reverse();
  }

  async statsSnapshot() {
    const now = Date.now();
    const c = this.seriesCache;
    // The numbers come from a database reader thread. Refresh at most every 10 s, and less often when the database is
    // big enough that a refresh takes long; never start a second refresh while one is still running.
    if ((!c || now - c.at > Math.max(10000, 5 * (c?.ms || 0))) && !this.statsBusy) {
      this.statsBusy = (async () => {
        const t0 = Date.now();
        try {
          const r = await this.store.stats(t0 - 24 * 3600000);
          this.seriesCache = { at: Date.now(), ms: Date.now() - t0, series: r.minuteSeries, topHosts: r.topHosts, topApps: r.topApps, rows: this.store.totalRows() };
        } catch (e) { console.error('[stats]', e.message); this.seriesCache = { ...(this.seriesCache || { series: [], topHosts: [], topApps: [], rows: 0 }), at: Date.now(), ms: 0 }; }
        finally { this.statsBusy = null; }
      })();
    }
    if (!this.seriesCache) await this.statsBusy;   // very first call: wait for the first numbers
    const sc = this.seriesCache || { series: [], topHosts: [], topApps: [], rows: 0 };
    return {
      uptimeSec: Math.round((now - this.totals.since) / 1000),
      received: this.totals.received, dropped: this.totals.dropped, bySeverity: this.totals.bySeverity,
      eps: this.currentEps(), peakEps: this.totals.peakEps, rate: this.rateSeries(),
      devices: this.devices.size, silentDevices: [...this.devices.values()].filter(d => d.silent).length, devicesIgnored: this.devicesIgnored || 0,
      db: { rows: sc.rows, sizeMB: Math.round(this.store.sizeMB() * 10) / 10, queueDropped: this.store.droppedOnOverflow },
      minuteSeries: sc.series, topHosts: sc.topHosts, topApps: sc.topApps,
      ruleHits: this.rules.hitCounts(), forwarders: [...this.forwarder.status(), ...this.trapForwarder.status()],
      health: this.health?.summary || { status: 'ok', warn: 0, bad: 0 },
      email: this.mail.status(), rawLog: { enabled: this.rawlog.enabled, error: this.rawlog.lastError }
    };
  }

  async maintenance() {
    if (this.maintaining) return; this.maintaining = true;
    const c = this.config.get();
    try {
      const n = await this.store.prune(c.retentionDays, c.maxDbMB);
      if (n) console.log(`[maintenance] pruned ${n} old messages`);
      const al = this.alarms?.prune?.(c.alarmRetentionDays < 0 || c.alarmRetentionDays === undefined ? c.retentionDays : c.alarmRetentionDays); if (al) console.log(`[maintenance] removed ${al} old cleared alarm(s)`);
      const f = this.rawlog.prune(c.retentionDays);
      if (f) console.log(`[maintenance] removed ${f} old raw log file(s)`);
    } catch (e) { console.error('[maintenance]', e.message); }
    finally { this.maintaining = false; }
  }

  shutdown() {
    for (const t of this.timers) clearInterval(t);
    this.persistDevices();
    this.rawlog.close();
  }
}

/** filter used for both the live buffer and the SSE stream */
function makeLiveFilter(q = {}) {
  const sevMax = q.severityMax === undefined || q.severityMax === '' ? null : +q.severityMax;
  const sevSet = parseSevs(q.sevs);
  const hosts = q.host ? String(q.host).split(',').map(s => s.trim().toLowerCase()).filter(Boolean) : null;
  const app = q.app ? String(q.app).toLowerCase() : null;
  const facility = q.facility === undefined || q.facility === '' ? null : +q.facility;
  const source = q.source === 'syslog' || q.source === 'snmp' ? q.source : null;
  const terms = [], tagTerms = [];
  for (const raw of (String(q.text || '').slice(0, 1000).match(/"[^"]+"|\S+/g) || []).slice(0, 8)) {
    let t = raw, neg = false;
    if (t.startsWith('-') && t.length > 1) { neg = true; t = t.slice(1); }
    t = t.replace(/^"|"$/g, '').toLowerCase();
    if (t.startsWith('tag:') && t.length > 4) tagTerms.push({ neg, t: t.slice(4) }); else terms.push({ neg, t });
  }
  // (no client-supplied regular expressions here: a pathological pattern would stall the receiver for every message)
  const re = null;
  return (m) => {
    if (sevMax !== null && SEVX.rank(m.severity) > SEVX.rank(sevMax)) return false;
    if (sevSet && !sevSet.includes(m.severity)) return false;
    if (facility !== null && m.facility !== facility) return false;
    if (source && (m.source || 'syslog') !== source) return false;
    if (hosts && !hosts.includes(m.host.toLowerCase()) && !hosts.includes(String(m.srcIp).toLowerCase())) return false;
    if (app && !(m.app || '').toLowerCase().includes(app)) return false;
    for (const x of tagTerms) if ((m.tags || []).some((g) => String(g).toLowerCase() === x.t) === x.neg) return false;
    if (terms.length || re) {
      const hay = `${m.message} ${m.host} ${m.app}`.toLowerCase();
      for (const x of terms) if (hay.includes(x.t) === x.neg) return false;
      if (re && !re.test(`${m.message} ${m.host} ${m.app}`)) return false;
    }
    return true;
  };
}

module.exports = { Engine, makeLiveFilter };
