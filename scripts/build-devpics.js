'use strict';
// 1.99.12 Builds public/devpics.js (the modern device pictures offered in Device view) from the drawings in assets/stencils.
// Run after changing a drawing:  node scripts/build-devpics.js
const fs = require('node:fs'); const path = require('node:path');
const dir = path.join(__dirname, '..', 'assets', 'stencils');
const LABEL = { 'switch-24port': 'Switch', 'switch-48port': 'Switch, 48 ports', 'server-1u': 'Server 1U', 'server-2u': 'Server 2U', 'server-tower': 'Tower server', 'rack-42u': 'Rack', 'rack-half': 'Half rack',
  'storage-nas': 'Storage / NAS', 'pc-desktop': 'Computer', 'pdu-strip': 'PDU', 'rectifier-shelf': 'Rectifier', 'battery-bank': 'Batteries', 'air-conditioner': 'Air conditioner', 'odf-patch-panel': 'Patch panel / ODF',
  'microwave-dish': 'Microwave dish', 'antenna-omni': 'Antenna', 'gps-clock': 'GPS / time server', 'audio-processor': 'Audio processor', 'wifi-access-point': 'Wi-Fi access point', 'sensor-temperature': 'Temperature sensor',
  'sensor-door': 'Door sensor', 'smoke-detector': 'Smoke detector', 'internet-globe': 'Internet', 'phone-ip': 'IP phone', 'controller-plc': 'Controller / PLC', 'fiber-media-converter': 'Media converter', ups: 'UPS' };
const cap = (k) => LABEL[k] || k.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
const out = {};
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.svg')).sort()) {
  const k = f.slice(0, -4);
  out[k] = [cap(k), fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s*\n\s*/g, '').replace(/\s{2,}/g, ' ').replace(/ width="160" height="160"/, '')];
}
const js = `'use strict';
// Generated by scripts/build-devpics.js from assets/stencils: do not edit by hand. Modern device pictures for Device view.
(() => {
  const P = ${JSON.stringify(out)};
  const url = (k) => (P[k] ? 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(P[k][1]) : '');
  window.NEPDevPics = { has: (k) => !!P[k], url, list: () => Object.entries(P).map(([k, v]) => ({ k, label: v[0] })) };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'devpics.js'), js);
console.log('public/devpics.js', Object.keys(out).length, 'pictures,', js.length, 'bytes');
